import os
from datetime import date, datetime
from decimal import Decimal, InvalidOperation

import psycopg
from psycopg.rows import dict_row
from flask import Flask, abort, flash, redirect, render_template, request, url_for, Response

app = Flask(__name__)
app.secret_key = os.getenv("FLASK_SECRET", "local-only-change-me")
DATABASE_URL = os.getenv("DATABASE_URL", "postgresql://postgres@localhost:5432/Crackers")


def db():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def init_db():
    with db() as conn:
        conn.execute("""
        CREATE TABLE IF NOT EXISTS products (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            source_no INTEGER UNIQUE, sku TEXT UNIQUE NOT NULL, barcode TEXT UNIQUE NOT NULL,
            category TEXT NOT NULL DEFAULT '', name TEXT NOT NULL,
            price NUMERIC(12,2) NOT NULL CHECK (price >= 0), active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE TABLE IF NOT EXISTS sales (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            invoice_no TEXT UNIQUE NOT NULL, customer TEXT NOT NULL DEFAULT '', customer_phone TEXT NOT NULL DEFAULT '',
            total NUMERIC(12,2) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE TABLE IF NOT EXISTS sale_items (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sale_id BIGINT NOT NULL REFERENCES sales(id), product_id BIGINT NOT NULL REFERENCES products(id),
            product_name TEXT NOT NULL, barcode TEXT NOT NULL, quantity INTEGER NOT NULL CHECK (quantity > 0),
            unit_price NUMERIC(12,2) NOT NULL, line_total NUMERIC(12,2) NOT NULL
        );
        """)
        conn.execute("ALTER TABLE sales ADD COLUMN IF NOT EXISTS customer_phone TEXT NOT NULL DEFAULT ''")


def money(value, field):
    try:
        amount = Decimal(value or "0")
        if not amount.is_finite() or amount < 0:
            raise InvalidOperation
        return amount.quantize(Decimal("0.01"))
    except (InvalidOperation, ValueError):
        raise ValueError(f"Enter a valid non-negative amount for {field}.")


def product_payload(p):
    return {k: (str(v) if isinstance(v, Decimal) else v) for k, v in p.items()}


@app.get("/")
def checkout():
    with db() as conn:
        products = conn.execute("SELECT * FROM products WHERE active ORDER BY category,name").fetchall()
    catalogue = [{"id": p["id"], "source_no": p["source_no"], "sku": p["sku"], "barcode": p["barcode"], "name": p["name"],
                 "category": p["category"], "price": str(p["price"])} for p in products]
    return render_template("checkout.html", products=products, catalogue=catalogue, today=date.today())


