@app.post("/products")
def save_product():
    try:
        name = request.form.get("name", "").strip()
        if not name:
            raise ValueError("Product name is required.")
        category = request.form.get("category", "").strip()
        price = money(request.form.get("price"), "price")
        with db() as conn:
            product_id = request.form.get("id")
            if product_id:
                if not conn.execute("SELECT id FROM products WHERE id=%s FOR UPDATE", (product_id,)).fetchone():
                    abort(404)
                conn.execute("UPDATE products SET name=%s,category=%s,price=%s,active=%s WHERE id=%s",
                             (name, category, price, request.form.get("active") == "on", product_id))
            else:
                new_id = conn.execute("SELECT nextval(pg_get_serial_sequence('products','id')) AS id").fetchone()["id"]
                sku, barcode = f"CRK{new_id:06d}", f"20{new_id:010d}"
                conn.execute("INSERT INTO products(id,sku,barcode,category,name,price) VALUES (%s,%s,%s,%s,%s,%s)",
                             (new_id, sku, barcode, category, name, price))
        flash("Product saved.", "success")
    except ValueError as exc:
        flash(str(exc), "error")
    except psycopg.errors.UniqueViolation:
        flash("That product code already exists. Refresh and try again.", "error")
    return redirect(url_for("products_page"))


